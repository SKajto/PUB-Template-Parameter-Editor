using System.Text.Json;
using System.Xml;
using Xunit;

namespace PubTemplateEditor.Integration.Tests;

/// <summary>
/// Guards the MSIX packaging configuration that CI uses. These checks are cheap
/// but catch the two failure modes that waste a whole CI cycle: a manifest that
/// MakeAppx rejects, and a submission build that silently ships placeholder identity.
/// </summary>
public class PackagingConfigurationTests
{
    private static string FindPackagingDir()
    {
        DirectoryInfo? dir = new(AppContext.BaseDirectory);
        for (int i = 0; i < 8 && dir is not null; i++, dir = dir.Parent)
        {
            string candidate = Path.Combine(dir.FullName, "packaging");
            if (File.Exists(Path.Combine(candidate, "AppxManifest.template.xml")))
            {
                return candidate;
            }
        }

        throw new DirectoryNotFoundException("packaging/ not found above the test assembly.");
    }

    private static string Template => File.ReadAllText(Path.Combine(FindPackagingDir(), "AppxManifest.template.xml"));

    [Fact]
    public void Template_uses_the_namespaces_makeappx_validates_against()
    {
        // The uap namespace is 'appx/manifest/uap/windows10'; the longer
        // 'foundation/windows10/universal' spelling is rejected by MakeAppx with
        // "does not recognize XML fields with namespace" (observed with SDK 10.0.22621/10.0.26100).
        XmlDocument doc = new();
        doc.LoadXml(Template.Replace("{{", "PLACEHOLDER_").Replace("}}", string.Empty));

        XmlNamespaceManager ns = new(doc.NameTable);
        ns.AddNamespace("p", "http://schemas.microsoft.com/appx/manifest/foundation/windows10");
        ns.AddNamespace("uap", "http://schemas.microsoft.com/appx/manifest/uap/windows10");
        ns.AddNamespace("rescap", "http://schemas.microsoft.com/appx/manifest/foundation/windows10/restrictedcapabilities");

        Assert.NotNull(doc.SelectSingleNode("/p:Package/p:Identity", ns));
        Assert.NotNull(doc.SelectSingleNode("/p:Package/p:Properties/p:DisplayName", ns));
        Assert.NotNull(doc.SelectSingleNode("/p:Package/p:Dependencies/p:TargetDeviceFamily", ns));
        Assert.NotNull(doc.SelectSingleNode("/p:Package/p:Applications/p:Application/uap:VisualElements", ns));
        Assert.NotNull(doc.SelectSingleNode("/p:Package/p:Capabilities/rescap:Capability", ns));

        XmlElement family = (XmlElement)doc.SelectSingleNode("/p:Package/p:Dependencies/p:TargetDeviceFamily", ns)!;
        Assert.Equal("Windows.Desktop", family.GetAttribute("Name"));

        XmlElement application = (XmlElement)doc.SelectSingleNode("/p:Package/p:Applications/p:Application", ns)!;
        Assert.Equal("PUB_Template_Parameter_Editor.exe", application.GetAttribute("Executable"));
        Assert.Equal("Windows.FullTrustApplication", application.GetAttribute("EntryPoint"));
    }

    [Fact]
    public void Template_references_only_assets_that_exist_after_the_asset_generator_runs()
    {
        string packagingDir = FindPackagingDir();
        XmlDocument doc = new();
        doc.LoadXml(Template.Replace("{{", "PLACEHOLDER_").Replace("}}", string.Empty));
        XmlNamespaceManager ns = new(doc.NameTable);
        ns.AddNamespace("p", "http://schemas.microsoft.com/appx/manifest/foundation/windows10");
        ns.AddNamespace("uap", "http://schemas.microsoft.com/appx/manifest/uap/windows10");

        List<string> referenced = new();
        foreach (XmlNode node in doc.SelectNodes("//@*", ns)!)
        {
            if (node.Value is not null && node.Value.StartsWith("assets\\", StringComparison.OrdinalIgnoreCase))
            {
                referenced.Add(node.Value);
            }
        }

        string logo = doc.SelectSingleNode("/p:Package/p:Properties/p:Logo", ns)!.InnerText;
        referenced.Add(logo);
        Assert.True(referenced.Count >= 5, "expected several tile references, found " + referenced.Count);

        foreach (string relative in referenced.Distinct())
        {
            // Provisional assets are generated by packaging/generate-placeholder-assets.ps1
            // during the packaging build; assert the generator covers every referenced file.
            string generator = File.ReadAllText(Path.Combine(packagingDir, "generate-placeholder-assets.ps1"));
            string fileName = Path.GetFileName(relative);
            Assert.Contains(fileName, generator, StringComparison.Ordinal);
        }
    }

    [Fact]
    public void TheManifestNamesTheExecutableThatTheProjectActuallyBuilds()
    {
        // The executable is named after the product, and the manifest has to name the same file the
        // build produces. Renaming one without the other yields a package that installs and then
        // refuses to start, which is exactly the kind of failure a test should catch.
        string root = Path.GetDirectoryName(FindPackagingDir())!;
        string project = File.ReadAllText(Path.Combine(root, "src", "PubTemplateEditor.App", "PubTemplateEditor.App.csproj"));
        string assembly = System.Text.RegularExpressions.Regex.Match(project, "<AssemblyName>([^<]+)</AssemblyName>").Groups[1].Value;
        Assert.False(string.IsNullOrWhiteSpace(assembly), "the app project must declare an assembly name");

        string manifest = File.ReadAllText(Path.Combine(root, "packaging", "AppxManifest.template.xml"));
        string executable = System.Text.RegularExpressions.Regex.Match(manifest, "Executable=\"([^\"]+)\"").Groups[1].Value;

        Assert.Equal(assembly + ".exe", executable);
        Assert.Equal("PUB_Template_Parameter_Editor", assembly);
    }

    [Fact]
    public void Draft_settings_still_contain_unresolved_identity_placeholders()
    {
        // REL-04: identity comes from the real reserved product. Until the owner supplies it,
        // the committed draft must keep REPLACE_* markers so a Strict build refuses to package.
        string json = File.ReadAllText(Path.Combine(FindPackagingDir(), "StoreRelease.settings.json"));
        using JsonDocument doc = JsonDocument.Parse(json);
        JsonElement root = doc.RootElement;

        foreach (string key in new[] { "productId", "packageIdentityName", "publisher", "publisherDisplayName" })
        {
            Assert.StartsWith("REPLACE_", root.GetProperty(key).GetString());
        }

        // The source repository is not an identity value, and it is no longer unknown: the project is
        // developed in the open at this URL, which is also where the GPL's corresponding source lives.
        Assert.Equal("https://github.com/SKajto/PUB-Template-Parameter-Editor",
            root.GetProperty("sourceRepositoryUrl").GetString());

        Assert.Equal("GPL-3.0-only", root.GetProperty("licenseExpression").GetString());
        Assert.Equal("x64", root.GetProperty("architecture").GetString());
        Assert.Equal("net10.0-windows", root.GetProperty("targetFramework").GetString());
        Assert.True(new Version(root.GetProperty("minVersion").GetString()!) >= new Version("10.0.22000.0"),
            "Windows 11 is the first supported OS");
        Assert.True(new Version(root.GetProperty("maxVersionTested").GetString()!) >= new Version("10.0.14393.0"),
            "maxVersionTested below 10.0.14393 makes the uap manifest namespace invalid");
    }
}
